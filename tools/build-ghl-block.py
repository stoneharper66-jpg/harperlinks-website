#!/usr/bin/env python3
"""Regenerate the GoHighLevel paste-block from the live site.

Run this after editing public/index.html so the GHL copy stays in sync:

    python3 tools/build-ghl-block.py

Output: ~/harperlinks-ghl/PASTE-INTO-GHL.html
"""
import base64
import pathlib
import re
import sys
from io import BytesIO

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "index.html"
LOGO = ROOT / "assets" / "logo-alpha.png"
DEST = ROOT / "ghl" / "PASTE-INTO-GHL.html"

GHL_RESET = """
/* ---------- GoHighLevel container reset (keep this at the top) ---------- */
body{margin:0!important;padding:0!important;overflow-x:hidden!important}
.hl_page-preview--content,#page-wrapper,.funnel-page,.c-section,.c-row,.c-column,
.c-wrapper,.inner,.row-fluid,section[id^="section"]{
  margin:0!important;padding:0!important;max-width:none!important;width:100%!important;
  background:transparent!important;border:0!important}
.c-section>.inner,.c-row>.inner{max-width:none!important;padding:0!important}
img{max-width:100%}
/* ------------------------------------------------------------------------ */
"""

HEADER = """<!--
  HARPERLINKS — paste-ready block for GoHighLevel
  ------------------------------------------------
  Paste this whole file into ONE "Custom JS/HTML" element on a BLANK GHL page.
  The logo is embedded, so there is nothing to upload.

  Before you paste, set the two links below (search for CONFIG):
    APP_URL      where the "Launch app" buttons should go
    CALENDAR_URL your GHL booking calendar link (optional)

  Generated by tools/build-ghl-block.py — do not hand-edit, regenerate instead.
-->"""

CONFIG_JS = """
/* ===================== CONFIG — edit these two ===================== */
var APP_URL      = "#";   /* e.g. your GHL funnel step, or the dashboard URL */
var CALENDAR_URL = "";    /* e.g. https://api.leadconnectorhq.com/widget/booking/XXXX */
/* =================================================================== */
(function(){
  var dest = (CALENDAR_URL && CALENDAR_URL.trim()) ? CALENDAR_URL : APP_URL;
  document.querySelectorAll('a[href="/app"]').forEach(function(a){
    a.setAttribute('href', dest);
    if(/^https?:/.test(dest)) { a.setAttribute('target','_blank'); a.setAttribute('rel','noopener'); }
  });
})();
"""


def section(text, open_tag, close_tag):
    """Return the content between the first open_tag and its matching close_tag."""
    start = text.index(open_tag) + len(open_tag)
    end = text.index(close_tag, start)
    return text[start:end]


def inline_logo():
    """Downscale the logo to WebP and return it as a data URI (keeps the paste small)."""
    try:
        from PIL import Image
    except ImportError:
        sys.exit("Pillow is required: pip3 install pillow")
    im = Image.open(LOGO).convert("RGBA")
    w = 700
    im = im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
    buf = BytesIO()
    im.save(buf, "WEBP", quality=75, method=6)
    return "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()


def main():
    src = SRC.read_text()
    css = section(src, "<style>", "</style>")
    body = section(src, "<body>", "<script>")
    js = section(src, "<script>", "</script>")

    # strip things GHL owns or that don't belong in a fragment
    body = re.sub(r'<a class="skip".*?</a>', "", body, flags=re.S)

    data_uri = inline_logo()
    for asset in ("assets/logo-alpha.png", "assets/logo-glow.png"):
        body = body.replace(asset, data_uri)

    out = (
        f"{HEADER}\n<style>{GHL_RESET}{css}</style>\n\n{body}\n"
        f"<script>{CONFIG_JS}</script>\n<script>\n{js}\n</script>\n"
    )
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text(out)
    print(f"wrote {DEST}  ({len(out)/1024:.0f} KB)")
    leftover = re.findall(r'(?:src|href)="(?:\.\./|/)?assets/', out)
    if leftover:
        print(f"WARNING: {len(leftover)} un-inlined asset ref(s) remain")


if __name__ == "__main__":
    main()
